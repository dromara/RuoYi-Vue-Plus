);

create table flow_event_wait (
    id bigint       not null primary key,
    tenant_id varchar(40)  default null,
    del_flag char(1)      default '0',
    definition_id bigint       default null,
    instance_id bigint       default null,
    node_code varchar(100) default null,
    event_type varchar(40)  not null,
    event_name varchar(100) default null,
    attached_task_id bigint       default null,
    trigger_type varchar(40)  default null,
    trigger_interval varchar(100) default null,
    next_trigger_at datetime     default null,
    timezone varchar(40)  default null,
    repeat_count int          default null,
    max_repeat_count int          default null,
    status varchar(20)  not null,
    retry_count int          default null,
    max_retry_count int          default null,
    retry_at datetime     default null,
    lock_owner varchar(64)  default null,
    lock_until datetime     default null,
    version int          default null,
    payload text,
    last_error varchar(500) default null,
    create_time datetime     default null,
    update_time datetime     default null
);
