-- Quant timestamps are normalized to UTC in DATETIME columns.
-- The production MySQL session was verified as SYSTEM / UTC+08:00 before this migration.
-- Only fields whose old writer is known to use Asia/Shanghai or SQL NOW/CURRENT_TIMESTAMP
-- under the verified +08:00 database clock are shifted. Exchange event timestamps and
-- Java-generated mixed-history audit timestamps are intentionally not touched.
--
-- Run exactly once after V20261104_01__account_trade_cycle_projection.sql.

-- Explicitly Beijing-local account snapshot time in the previous implementation.
UPDATE quant_account_snapshot
SET observed_at = DATE_SUB(observed_at, INTERVAL 8 HOUR);

-- SQL-generated audit timestamps (old writer used NOW/CURRENT_TIMESTAMP on SYSTEM +08:00).
UPDATE quant_strategy_entry_guard
SET created_at = DATE_SUB(created_at, INTERVAL 8 HOUR);

UPDATE quant_strategy_order_intent
SET created_at = DATE_SUB(created_at, INTERVAL 8 HOUR);

UPDATE quant_strategy_fill_journal
SET created_at = DATE_SUB(created_at, INTERVAL 8 HOUR),
    updated_at = DATE_SUB(updated_at, INTERVAL 8 HOUR),
    last_attempt_at = CASE WHEN last_attempt_at IS NULL THEN NULL
                           ELSE DATE_SUB(last_attempt_at, INTERVAL 8 HOUR) END;

UPDATE quant_strategy_fill_allocation
SET created_at = DATE_SUB(created_at, INTERVAL 8 HOUR);

UPDATE quant_strategy_fill_sync_cursor
SET updated_at = DATE_SUB(updated_at, INTERVAL 8 HOUR);

UPDATE quant_financial_event_sync_cursor
SET updated_at = DATE_SUB(updated_at, INTERVAL 8 HOUR);

UPDATE quant_strategy_position_inventory
SET updated_at = DATE_SUB(updated_at, INTERVAL 8 HOUR);

UPDATE quant_position_sync_fence
SET updated_at = DATE_SUB(updated_at, INTERVAL 8 HOUR);

-- The account-wide cycle projection tables were introduced by V20261104_01 and
-- their audit fields were generated by NOW(3); opened_at / closed_at / trade_time
-- are exchange event facts already stored as UTC and must not be shifted.
UPDATE quant_trade_cycle_scope
SET updated_at = DATE_SUB(updated_at, INTERVAL 8 HOUR);

UPDATE quant_trade_cycle
SET created_at = DATE_SUB(created_at, INTERVAL 8 HOUR),
    updated_at = DATE_SUB(updated_at, INTERVAL 8 HOUR);

UPDATE quant_trade_cycle_fill
SET created_at = DATE_SUB(created_at, INTERVAL 8 HOUR);

